// Builds dist/sdk.js (minified IIFE the edge server injects), dist/sdk.mjs (ESM for
// bundlers) and dist/sdk.d.ts (public types, copied from src/types.ts).
import { build } from "esbuild";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { gzipSync } from "node:zlib";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const pkg = JSON.parse(readFileSync(root + "package.json", "utf8"));

const common = {
  absWorkingDir: root,
  entryPoints: ["src/index.ts"],
  bundle: true,
  target: "es2019",
  define: { __VERSION__: JSON.stringify(pkg.version) },
  banner: { js: `/*! ${pkg.name} ${pkg.version} */` },
  legalComments: "none",
  logLevel: "warning",
};

mkdirSync(root + "dist", { recursive: true });
await build({ ...common, format: "iife", minify: true, outfile: "dist/sdk.js" });
await build({ ...common, format: "esm", minify: false, outfile: "dist/sdk.mjs" });

const types = readFileSync(root + "src/types.ts", "utf8");
const dts = `/*! ${pkg.name} ${pkg.version} */
// Generated by scripts/build.mjs from src/types.ts. Do not edit.

${types.trimEnd()}

declare const DegenHive: DegenHiveApi;
export default DegenHive;
export { DegenHive };

declare global {
  /** The SDK. The server adds it to every HTML page of a build. */
  const DegenHive: DegenHiveApi;
  interface Window {
    DegenHive: DegenHiveApi;
  }
  interface WindowEventMap {
    "degenhive:ready": CustomEvent<DegenHiveApi>;
  }
}
`;
writeFileSync(root + "dist/sdk.d.ts", dts);

const js = readFileSync(root + "dist/sdk.js");
console.log(`dist/sdk.js ${js.length} bytes, ${gzipSync(js).length} gzipped`);
